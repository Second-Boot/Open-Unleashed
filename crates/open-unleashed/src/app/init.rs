//! `App::new`: the application's state at start-up, built from what `main::run` read (`AppInit`).
//! The literal is `run`'s, moved as it was: every field keeps its
//! initialiser and the source order (an initialiser that reads the environment or the clock reads
//! it at the same point of the start-up as before).

use crate::*;

/// What `main::run` read before building the [`App`]: the command line's choices, the loaded
